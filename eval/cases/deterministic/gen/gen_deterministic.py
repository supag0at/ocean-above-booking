def save_pref(value):
    # save_preference: candidates=[value], original NOT used
    items = w.by_norm.get(norm(value), [])
    if len(items) == 1:
        return {"ok": True, "stored": items[0]}
    if len(items) > 1:
        return {"ok": False, "code": "CITY_AMBIGUOUS", "candidates": sorted(items)}
    sug = resolve(w, "\u0000", [value])
    return {"ok": False, "code": "INVALID_INPUT", "candidates": [m["city"] for m in sug["matches"]][:5]}


