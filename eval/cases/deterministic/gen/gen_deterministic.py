# 8-leg routes: pick the lexicographically first pair among 8-leg ones (computed, slow-ish)
def eight_leg_example():
    D, P = {}, {}
    for x in w.hubs:
        for y in w.hubs:
            if x == y:
                D[x, y], P[x, y] = 0.0, [x]
            else:
                r = w.route(x, y); D[x, y], P[x, y] = r["totalDistanceKm"], r["path"]
    ends = {c: ([(c, 0.0)] if w.is_hub[c] else [(h, w.d(c, h)) for h in w.conn[c]]) for c in w.cities if w.served(c)}
    for a in sorted(ends):
        for b in sorted(ends):
            if a == b:
                continue
            _, ha, hb = min((da + D[x, y] + db, x, y) for x, da in ends[a] for y, db in ends[b])
            path = ([a] if a != ha else []) + P[ha, hb] + ([b] if b != hb else [])
            if len(path) - 1 == 8:
                return a, b
